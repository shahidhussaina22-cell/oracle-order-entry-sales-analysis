-- Project: Oracle OE Sales Analysis
-- 
-- Objective: Analyze revenue trends by month, quarter, and year

-- 1. Monthly Revenue Trends
SELECT
    TO_CHAR(TRUNC(ORDER_DATE, 'MM'), 'YYYY') AS YEAR,
    TO_CHAR(ORDER_DATE, 'Q') AS QUARTER,
    TO_CHAR(TRUNC(ORDER_DATE, 'MM'), 'FMMonth') AS MONTH,
    TO_CHAR(TRUNC(ORDER_DATE, 'MM'), 'MM') AS MONTH_NUMBER,
    ROUND(SUM(ORDER_TOTAL), 2) AS TOTAL_REVENUE
FROM OE.ORDERS
GROUP BY 
    TRUNC(ORDER_DATE, 'MM'),
    TO_CHAR(ORDER_DATE, 'Q')
ORDER BY TRUNC(ORDER_DATE, 'MM');


-- 2. Quarterly Revenue Trends
SELECT
    TO_CHAR(TRUNC(ORDER_DATE, 'YYYY'), 'YYYY') AS YEAR,
    TO_CHAR(ORDER_DATE, 'Q') AS QUARTER,
    ROUND(SUM(ORDER_TOTAL), 2) AS TOTAL_REVENUE
FROM OE.ORDERS
GROUP BY
    TRUNC(ORDER_DATE, 'YYYY'),
    TO_CHAR(ORDER_DATE, 'Q')
ORDER BY
    TRUNC(ORDER_DATE, 'YYYY'),
    TO_CHAR(ORDER_DATE, 'Q');


-- 3. Yearly Revenue Trends
SELECT
    TO_CHAR(TRUNC(ORDER_DATE, 'YYYY'), 'YYYY') AS YEAR,
    ROUND(SUM(ORDER_TOTAL), 2) AS TOTAL_REVENUE
FROM OE.ORDERS
GROUP BY TRUNC(ORDER_DATE, 'YYYY')
ORDER BY TRUNC(ORDER_DATE, 'YYYY');
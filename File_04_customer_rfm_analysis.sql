-- 1. Customer RFM Metrics

SELECT
    CUSTOMER_ID,
    MAX(ORDER_DATE) AS LAST_ORDER_DATE,
    TRUNC(SYSDATE) - TRUNC(MAX(ORDER_DATE)) AS RECENCY_DAYS,
    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
    ROUND(SUM(ORDER_TOTAL), 2) AS TOTAL_REVENUE
FROM OE.ORDERS
GROUP BY CUSTOMER_ID
ORDER BY TOTAL_REVENUE DESC;


-- 2. Customer Revenue Segmentation

WITH customer_metrics AS (
    SELECT
        CUSTOMER_ID,
        MAX(ORDER_DATE) AS LAST_ORDER_DATE,
        TRUNC(SYSDATE) - TRUNC(MAX(ORDER_DATE)) AS RECENCY_DAYS,
        COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
        SUM(ORDER_TOTAL) AS TOTAL_REVENUE
    FROM OE.ORDERS
    GROUP BY CUSTOMER_ID
)
SELECT
    CUSTOMER_ID,
    RECENCY_DAYS,
    TOTAL_ORDERS,
    ROUND(TOTAL_REVENUE, 2) AS TOTAL_REVENUE,
    CASE
        WHEN RECENCY_DAYS > 180
             AND TOTAL_REVENUE <= 10000
            THEN 'At Risk'
        WHEN TOTAL_REVENUE >= 100000
            THEN 'High Value'
        WHEN TOTAL_REVENUE >= 50000
            THEN 'Medium Value'
        WHEN TOTAL_REVENUE > 10000
            THEN 'Low Value'
        ELSE 'Low Value / Review'
    END AS CUSTOMER_SEGMENT
FROM customer_metrics
ORDER BY TOTAL_REVENUE DESC;


-- 3. Top 10 Customers by Revenue Contribution

WITH customer_revenue AS (
    SELECT
        CUSTOMER_ID,
        SUM(ORDER_TOTAL) AS REVENUE
    FROM OE.ORDERS
    GROUP BY CUSTOMER_ID
),
ranked_customers AS (
    SELECT
        CUSTOMER_ID,
        REVENUE,
        SUM(REVENUE) OVER () AS TOTAL_REVENUE,
        ROW_NUMBER() OVER (
            ORDER BY REVENUE DESC, CUSTOMER_ID
        ) AS REVENUE_RANK
    FROM customer_revenue
)
SELECT
    CUSTOMER_ID,
    ROUND(REVENUE, 2) AS REVENUE,
    ROUND(TOTAL_REVENUE, 2) AS OVERALL_REVENUE,
    ROUND(REVENUE / NULLIF(TOTAL_REVENUE, 0) * 100, 2)
        AS REVENUE_PERCENT,
    REVENUE_RANK
FROM ranked_customers
WHERE REVENUE_RANK <= 10
ORDER BY REVENUE_RANK;
